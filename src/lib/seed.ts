import type {
  Client, Employee, ExpenseWithAlocari, Income, Obligation, Project, Settings, Workday,
} from "@/lib/types";

export type DataState = {
  clients: Client[];
  projects: Project[];
  expenses: ExpenseWithAlocari[];
  incomes: Income[];
  employees: Employee[];
  workdays: Workday[];
  obligations: Obligation[];
  settings: Settings;
};

function iso(d: Date): string {
  return d.toISOString().slice(0, 10);
}
function daysAgo(base: Date, n: number): string {
  const d = new Date(base);
  d.setDate(d.getDate() - n);
  return iso(d);
}
function mondayWeeksAgo(base: Date, weeks: number): string {
  const d = new Date(base);
  d.setDate(d.getDate() - weeks * 7);
  const dow = (d.getDay() + 6) % 7; // 0 = luni
  d.setDate(d.getDate() - dow);
  return iso(d);
}

/** Construieste un set proaspat de date, cu datele calendaristice relative la ACUM
 *  (deci dashboard-ul arata mereu populat, indiferent cand e vizitat demo-ul). */
export function freshSeed(): DataState {
  const now = new Date();
  const nowISO = new Date().toISOString();
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, "0");

  const clients: Client[] = RAW.clients.map((c) => ({
    id: c.id, nume: c.nume, tip: c.tip as Client["tip"], email: c.email, created_at: nowISO,
  }));
  const projects: Project[] = RAW.projects.map((p) => ({
    id: p.id, client_id: p.client_id, nume: p.nume, locatie: p.locatie,
    client_final: p.client_final, status: p.status as Project["status"],
    oferta_total: p.oferta_total, data_start: daysAgo(now, p.daysAgo_start),
    data_estimata_incasare: p.daysAgo_est == null ? null : daysAgo(now, p.daysAgo_est),
    created_at: nowISO,
  }));
  const expenses: ExpenseWithAlocari[] = RAW.expenses.map((e) => ({
    id: e.id, data: daysAgo(now, e.daysAgo), suma_total: e.suma_total,
    grupa: e.grupa as ExpenseWithAlocari["grupa"], categorie: e.categorie as ExpenseWithAlocari["categorie"],
    descriere: e.descriere, furnizor: e.furnizor, locatie: e.locatie, declarat: e.declarat,
    created_at: nowISO, alocari: e.alocari.map((a) => ({ project_id: a.project_id, suma: a.suma })),
  }));
  const incomes: Income[] = RAW.incomes.map((i) => ({
    id: i.id, project_id: i.project_id, data: daysAgo(now, i.daysAgo), suma: i.suma,
    tip: i.tip as Income["tip"], declarat: i.declarat, mod_plata: i.mod_plata as Income["mod_plata"],
    created_at: nowISO,
  }));
  const employees: Employee[] = RAW.employees.map((e) => ({
    id: e.id, nume: e.nume, rata_zi: e.rata_zi, activ: e.activ,
  }));
  const workdays: Workday[] = RAW.workdays.map((w) => ({
    id: w.id, employee_id: w.employee_id, project_id: w.project_id,
    week_start: mondayWeeksAgo(now, w.weekMondayAgo), zile: w.zile,
  }));
  const obligations: Obligation[] = RAW.obligations.map((o) => ({
    id: o.id, descriere: o.descriere, suma: o.suma,
    scadenta: `${y}-${m}-${String(o.dayOfMonth).padStart(2, "0")}`,
    recurenta: o.recurenta as Obligation["recurenta"], achitat: o.achitat,
  }));
  const settings: Settings = {
    id: 1, sold_curent: RAW.settings.sold_curent,
    sold_updated_at: daysAgo(now, RAW.settings.daysAgo_soldUpdated),
    marja_neprevazut_setata: RAW.settings.marja_neprevazut_setata,
    marja_pierderi_setata: RAW.settings.marja_pierderi_setata,
  };
  return { clients, projects, expenses, incomes, employees, workdays, obligations, settings };
}
